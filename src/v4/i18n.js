function storedLang() {
  try {
    return localStorage.getItem(LANG_KEY) || '';
  } catch (_e) {
    return '';
  }
}

function settingsDefaultLang() {
  try {
    const s = JSON.parse(localStorage.getItem('hr:settings:v1') || '{}');
    if (s.language) {
      return s.language;
    }
    return s.company && s.company.defaultLang ? s.company.defaultLang : '';
  } catch (_e) {
    return '';
  }
}

export function currentLang() {
  const l = storedLang() || settingsDefaultLang() || 'en';
  return l === 'ar' ? 'ar' : 'en';
}

export function t(key) {
  const lang = currentLang();
  return (STR[lang] && STR[lang][key]) || STR.en[key] || key;
}

export function applyI18n(root = document) {
  const lang = currentLang();
  root.querySelectorAll('[data-i18n]').forEach(el => {
    const v = STR[lang][el.getAttribute('data-i18n')] || STR.en[el.getAttribute('data-i18n')];
    if (v) {
      el.textContent = v;
    }
  });
  root.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const v = STR[lang][el.getAttribute('data-i18n-ph')] || STR.en[el.getAttribute('data-i18n-ph')];
    if (v) {
      el.setAttribute('placeholder', v);
    }
  });
}

function slugifyLabel(label) {
  return (label || '')
    .toLowerCase()
    .replace(/[^a-z]+/g, '-')
    .replace(/^-|-$/g, '');
}

// Translate build-time-injected shell (sidebar + topbar) by stable href/label lookup.
export function applyShellI18n() {
  const groups = document.querySelectorAll('.sidebar .nav-group');
  groups.forEach((g, gi) => {
    const def = NAV[gi];
    if (!def) {
      return;
    }
    const label = g.querySelector('.nav-label');
    if (label) {
      label.textContent = t(`navgroup.${slugifyLabel(def.label)}`);
    }
    def.items.forEach(item => {
      if (!item.children) {
        const a = g.querySelector(`a[href="${item.href}"] .nav-text`);
        if (a) {
          a.textContent = t(`nav.${item.key}`);
        }
        return;
      }
      // Submenu children: HR leaves only (non-HR children keep static text,
      // since t() falls back to the raw key when no translation exists).
      for (const c of item.children) {
        if (c.children) {
          // Nested parent (template groups under HR → Settings): label via
          // its i18n key, grandchildren via nav.* only when translated.
          if (c.i18n && c.children[0]) {
            const sub = g
              .querySelector(`a.nav-sublink[href="${c.children[0].href}"]`)
              ?.closest('.nav-subtree');
            const lbl = sub?.querySelector('.nav-subtoggle .nav-text');
            if (lbl) {
              lbl.textContent = t(c.i18n);
            }
          }
          for (const gc of c.children) {
            const k = `nav.${gc.key}`;
            if (t(k) === k) {
              continue;
            }
            const s = g.querySelector(`a.nav-sublink[href="${gc.href}"] .nav-text`);
            if (s) {
              s.textContent = t(k);
            }
          }
          continue;
        }
        if (!c.key || !c.key.startsWith('hr-')) {
          continue;
        }
        const s = g.querySelector(`a.nav-sublink[href="${c.href}"] .nav-text`);
        if (s) {
          s.textContent = t(`nav.${c.key}`);
        }
      }
      if (item.i18n) {
        const first = item.children[0];
        const tree =
          first && g.querySelector(`a.nav-sublink[href="${first.href}"]`)?.closest('.nav-tree');
        const lbl = tree?.querySelector('.nav-toggle .nav-text');
        if (lbl) {
          lbl.textContent = t(item.i18n);
        }
      }
    });
  });
  const search = document.querySelector('.topbar .search-box input');
  if (search) {
    search.setAttribute('placeholder', t('common.searchPh'));
  }
  const toggle = document.getElementById('lang-toggle');
  if (toggle) {
    toggle.textContent = currentLang() === 'ar' ? 'EN' : 'عربي';
  }
}

/** Apply owner brand (name + logo) to the sidebar. Only when saved in Settings. */
export function applyBranding() {
  let stored = null;
  try {
    stored = JSON.parse(localStorage.getItem('hr:settings:v1') || 'null');
  } catch (_e) {
    /* private mode */
  }
  const sc = (stored && stored.company) || {};
  const raw = {
    company: {
      nameEn: sc.nameEn || SEED_COMPANY.nameEn,
      nameAr: sc.nameAr || SEED_COMPANY.nameAr,
      logo: sc.logo || SEED_COMPANY.logoUrl,
      primary: sc.primary || SEED_COMPANY.primary
    }
  };
  if (!raw.company.nameEn) {
    return;
  }
  const lang = currentLang();
  const name = lang === 'ar' ? raw.company.nameAr || raw.company.nameEn : raw.company.nameEn;
  // White-label: browser tab + theme color follow the company profile.
  const base = (document.title.split('|')[0] || '').trim() || name;
  document.title = `${base} | ${String(name).replace(/\|/g, ' ')}`;
  const hex = raw.company.primary;
  if (/^#[0-9a-fA-F]{6}$/.test(hex || '')) {
    const r = parseInt(hex.slice(1, 3), 16);
    const g = parseInt(hex.slice(3, 5), 16);
    const b = parseInt(hex.slice(5, 7), 16);
    const dk = [r, g, b].map(v => Math.round(v * 0.85));
    const root = document.documentElement.style;
    root.setProperty('--primary', hex);
    root.setProperty('--primary-lt', `rgba(${r},${g},${b},0.06)`);
    root.setProperty('--primary-dk', `rgb(${dk[0]},${dk[1]},${dk[2]})`);
    root.setProperty('--sidebar-active', `rgba(${r},${g},${b},0.08)`);
  }
  const brandName = document.querySelector('.sidebar-brand .brand-name');
  if (brandName) {
    brandName.textContent = name;
  }
  const icon = document.querySelector('.sidebar-brand .brand-icon');
  if (icon) {
    if (raw.company.logo) {
      icon.innerHTML = '';
      const img = document.createElement('img');
      img.src = raw.company.logo;
      img.alt = name;
      img.style.cssText = 'width:100%;height:100%;object-fit:contain;border-radius:inherit';
      icon.appendChild(img);
    } else if (!icon.querySelector('img')) {
      icon.textContent = (name || 'H').trim().charAt(0);
    }
  }
}

export function setLang(lang) {
  const next = lang === 'ar' ? 'ar' : 'en';
  try {
    localStorage.setItem(LANG_KEY, next);
  } catch (_e) {
    /* private mode */
  }
  document.documentElement.setAttribute('lang', next);
  document.documentElement.setAttribute('dir', next === 'ar' ? 'rtl' : 'ltr');
  applyI18n(document);
  applyShellI18n();
  applyBranding();
  window.dispatchEvent(new CustomEvent(LANG_EVENT, { detail: { lang: next } }));
}

let inited = false;

export function initI18n() {
  if (inited) {
    return;
  }
  inited = true;
  const lang = currentLang();
  document.documentElement.setAttribute('lang', lang);
  document.documentElement.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
  // Inject language toggle into topbar (replaces external docs link for internal tool).
  const docs = document.querySelector('.topbar .tb-docs');
  if (docs && !document.getElementById('lang-toggle')) {
    const btn = document.createElement('button');
    btn.type = 'button';
    btn.id = 'lang-toggle';
    btn.className = 'tb-btn tb-lang';
    btn.title = 'Language / اللغة';
    btn.setAttribute('aria-label', 'Switch language');
    docs.replaceWith(btn);
    btn.addEventListener('click', () => setLang(currentLang() === 'ar' ? 'en' : 'ar'));
  }
  applyI18n(document);
  applyShellI18n();
  applyBranding();
}
